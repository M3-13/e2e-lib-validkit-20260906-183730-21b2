_NON_DIGITS = re.compile(r"\D")


def _country_code_to_int(country_code: str | int) -> int:
    if isinstance(country_code, int):
        digits = str(country_code)
    else:
        digits = country_code.strip()
        if digits.startswith("+"):
            digits = digits[1:]
    if not digits.isdigit():
        raise ValueError(f"country_code must contain digits only, got {country_code!r}")
    return int(digits)


def normalize_phone(text: str, country_code: str | int) -> str:
    if not isinstance(text, str):
        raise TypeError(f"text must be a str, got {type(text).__name__}")

    if isinstance(country_code, bool) or not isinstance(country_code, (str, int)):
        raise TypeError(f"country_code must be a str or int, got {type(country_code).__name__}")

    cc = _country_code_to_int(country_code)
    if cc not in _COUNTRY_CODES:
        raise ValueError(f"unknown country code: {country_code!r}")

    digits = _NON_DIGITS.sub("", text)
    if not digits:
        raise ValueError("phone number contains no digits")

    national = digits
    if national.startswith(str(cc)):
        national = national[len(str(cc)) :]
    national = national.lstrip("0")

    if not national:
        raise ValueError("phone number is empty after normalization")

    return f"+{cc}{national}"
